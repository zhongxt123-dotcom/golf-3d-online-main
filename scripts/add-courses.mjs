// ─── 生成标签规则 ─────────────────────────────
function generateTags(name, province) {
  const t = name + province;
  const strategy = /林克斯|林克司|松石|风|海岸|海滨|海风|Links/i.test(t) ? "进取型/重炮手" : "稳健型/控球派";
  const terrain = /山|峰|峡谷|高原|雪山|森林|林地|石|红枫/i.test(t) ? "山地球场爱好者"
    : /湖|水|湿地|河|岛|湾|溪|海|沙/i.test(t) ? "水障恐慌者"
    : "沙坑挑战者";
  const env = /海南|三亚|热带|广东|广西|福建/i.test(t) ? "怕热星人"
    : /风|海|滨海/i.test(t) ? "体能充沛"
    : "抗风能力弱";
  const diff = (/锦标赛|大师|公开赛|职业|世界杯|名人赛|PGA|TPC|国际|挑战|尼克劳斯|金熊|佘山|观澜|隐秀/.test(t))
    ? "职业水准" : (/乡村|公众|太阳岛|假日|度假/.test(t) ? "新手上路" : "业余高手");
  return { strategy, terrain, environment: env, skill: diff };
}

